/***************************************************************************
  函数名称：display_menu
  功    能：显示菜单选项
  输入参数：
  返 回 值：
  说    明：
***************************************************************************/
void display_menu(const char* menus[])
{
	for (int i = 0; menus[i] != ""; i++)
	{
		cout << menus[i];
		if(menus[i+1] != "")
			cout << endl;
	}
}
/***************************************************************************
函数名称：select_op
功    能：
输入参数：
返 回 值：对应选项
说    明：
***************************************************************************/
int select_op(const char* valid_chars)
{
	while (1) 
	{
		char op = _getch();
		for (int i = 0; valid_chars[i] != '\0'; i++) 
		{
			if (op == valid_chars[i] || op == tolower(valid_chars[i])) 
			{
				//cout << op;
				return toupper(op);
			}
		}
	}
}
