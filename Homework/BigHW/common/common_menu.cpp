int hanoi_menu()
{
	cct_cls();
	cct_setfontsize("新宋体", 16, 8);
	cct_setcursor(CCT_CURSOR_VISIBLE_NORMAL);
	cct_setconsoleborder(120, 40, 120, 9001);
	display_menu(hanoi_menus);
	char op = select_op("0123456789");
	return op - '0';
}

