int jc(int n)
{
    if (n == 0)
        return 1;
    else
    {
        int t = 1;
        for (int i = 1; i <= n; i++)
            t *= i;
        return t;
    }
}
int tri(int n, int m)
{
    return jc(n) / (jc(m) * jc(n - m));
}
